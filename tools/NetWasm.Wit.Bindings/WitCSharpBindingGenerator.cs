using System;
using System.Reflection;
using NetWasm.Wit.Bindings.TypeDefinitions;

namespace NetWasm.Wit.Bindings;

public interface IWitCSharpBindingGenerator
{
    // The namespace defaults to one derived from the world's package.
    string Generate(WitDocument document, WitWorld world, string? namespaceName = null);
}

public sealed class WitCSharpBindingGenerator(
    IWitWorldValidator validator,
    IWitTypeDeclarationWriter typeDeclarations,
    IWitBindingMethodWriter bindingMethods,
    IWitCanonicalMarshallingWriter marshalling,
    IWitBindingSyntaxFormatter syntax,
    ICodeWriterFactory writers,
    IWitTypeDefinitionClassifier definitions) : IWitCSharpBindingGenerator
{
    private readonly IWitWorldValidator _validator = validator ??
        throw new ArgumentNullException(nameof(validator));
    private readonly IWitTypeDeclarationWriter _typeDeclarations = typeDeclarations ??
        throw new ArgumentNullException(nameof(typeDeclarations));
    private readonly IWitBindingMethodWriter _bindingMethods = bindingMethods ??
        throw new ArgumentNullException(nameof(bindingMethods));
    private readonly IWitCanonicalMarshallingWriter _marshalling = marshalling ??
        throw new ArgumentNullException(nameof(marshalling));
    private readonly IWitBindingSyntaxFormatter _syntax = syntax ??
        throw new ArgumentNullException(nameof(syntax));
    private readonly ICodeWriterFactory _writers = writers ??
        throw new ArgumentNullException(nameof(writers));
    private readonly IWitTypeDefinitionClassifier _definitions = definitions ??
        throw new ArgumentNullException(nameof(definitions));

    // The generator's release, without build metadata.
    private static readonly string Version =
        typeof(WitCSharpBindingGenerator).Assembly
            .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion.Split('+')[0] ?? "unknown";

    public string Generate(WitDocument document, WitWorld world, string? namespaceName = null)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(world);
        _validator.Validate(document, world);
        document = NameTypes(document, world);

        var writer = _writers.Create();
        writer.Line("// <auto-generated />");
        writer.Line($"// Generated by netwasm-wit-bindgen {Version}");
        writer.Line("#nullable enable");
        writer.Line("using System;");
        writer.Line("using System.Runtime.InteropServices.WebAssembly;");
        writer.Line();
        writer.Line($"namespace {namespaceName ?? _syntax.Format(
            new WitBindingSyntaxRequest.PackageNamespace(world.Package))};");
        writer.Line();
        writer.Raw(_typeDeclarations.Generate(document, world));
        writer.Raw(_bindingMethods.Generate(document, world));
        writer.Raw(_marshalling.Generate(document, world));
        return writer.Text;
    }

    // The types the bindings declare share one namespace: an interface's type
    // whose name collides with another's is qualified by the interface, then
    // by its package; a world's own type by the world. Aliases, including the
    // ones `use` makes, declare nothing: they are the type they name.
    private WitDocument NameTypes(WitDocument document, WitWorld world)
    {
        string Identifier(string value) => _syntax.Format(new WitBindingSyntaxRequest.Identifier(value));
        var declarations = new List<(int Key, string[] Candidates)>();
        foreach (var item in world.Imports.Concat(world.Exports)
                     .Where(static item => item.InterfaceId is not null)
                     .DistinctBy(static item => item.InterfaceId))
        {
            var definition = document.Interfaces[item.InterfaceId!.Value];
            var owner = Identifier(WitBindingNames.Short(item, definition));
            var package = Identifier(WitBindingNames.Qualifier(item, definition, world));
            foreach (var id in definition.Types.Values)
            {
                if (document.Types[id].Name is { } name && Declares(document.Types[id]))
                {
                    declarations.Add((id, [Identifier(name), owner + Identifier(name), package + owner + Identifier(name)]));
                }
            }
        }
        foreach (var id in world.Types.Values)
        {
            if (document.Types[id].Name is { } name && Declares(document.Types[id]))
            {
                declarations.Add((id, [Identifier(name), Identifier(world.Name) + Identifier(name)]));
            }
        }
        var names = WitBindingNames.Assign(declarations, "types");
        return document with
        {
            Types =
            [
                .. document.Types.Select(type => names.TryGetValue(type.Id, out var name) &&
                    name != Identifier(type.Name!)
                        ? type with { BindingName = name }
                        : type),
            ],
        };
    }

    private bool Declares(WitTypeDefinition type) =>
        _definitions.Classify(type) != WitTypeDefinitionCategory.TransparentAlias;
}
