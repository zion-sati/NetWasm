// Generates a reflection-free table of every benchmark case in a set of
// dotnet/performance micro-benchmark sources: construction, [Params] values,
// [GlobalSetup], and each [Arguments] set, as plain C# the runner calls.
// usage: Generator <output.cs> <exclusions.txt|-> <source files or directories...>
// run.py builds and runs it; see README.md.
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

var output = args[0];
var exclusions = args[1] == "-" ? [] : File.ReadAllLines(args[1])
    .Select(line => line.Split('#')[0].Trim()).Where(line => line.Length > 0).ToHashSet();
var files = args.Skip(2).SelectMany(path => Directory.Exists(path)
        ? Directory.EnumerateFiles(path, "*.cs", SearchOption.AllDirectories)
        : [path])
    .Where(file => !exclusions.Any(excluded => file.Replace('\\', '/').Contains(excluded)))
    .OrderBy(file => file, StringComparer.Ordinal)
    .ToArray();
// The symbols every runtime's build defines, so the table names only code all of them compile.
var parse = new CSharpParseOptions(LanguageVersion.Preview, preprocessorSymbols:
    ["RELEASE", "TRACE", "NETCOREAPP", "NET5_0_OR_GREATER", "NET6_0_OR_GREATER", "NET7_0_OR_GREATER", "NET8_0_OR_GREATER",
     "NET9_0_OR_GREATER", "NET10_0_OR_GREATER"]);
var trees = files.Select(file => CSharpSyntaxTree.ParseText(File.ReadAllText(file), parse, file)).ToArray();
var runtime = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
var references = Directory.EnumerateFiles(runtime, "*.dll")
    .Where(file => !file.Contains("Native", StringComparison.Ordinal))
    .Select(file => MetadataReference.CreateFromFile(file));
var compilation = CSharpCompilation.Create("Benchmarks", trees, references,
    new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true, nullableContextOptions: NullableContextOptions.Enable));
var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
if (errors.Length > 0)
{
    foreach (var error in errors.Take(400)) Console.Error.WriteLine(error);
    Console.Error.WriteLine($"{errors.Length} errors");
    // One line per file that does not compile, for the exclusion loop.
    foreach (var file in errors.Select(error => error.Location.SourceTree?.FilePath).Where(path => path is not null).Distinct())
        Console.WriteLine($"uncompiled\t{file}");
    return 2;
}

var full = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
    SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
string Name(ITypeSymbol type) => type.ToDisplayString(full);
// An array argument renders as an array creation; the others as a cast constant.
string Literal(TypedConstant value, ITypeSymbol type) =>
    value.Kind == TypedConstantKind.Array && type is IArrayTypeSymbol array
        ? $"new {Name(array.ElementType)}[] {{ {string.Join(", ", value.Values.Select(element => Literal(element, array.ElementType)))} }}"
        : $"({Name(type)})({value.ToCSharpString()})";
bool Is(AttributeData attribute, string name) => attribute.AttributeClass?.ToDisplayString() == $"BenchmarkDotNet.Attributes.{name}Attribute";

var code = new StringBuilder();
var skipped = new List<string>();
var count = 0;
code.AppendLine("// <auto-generated/> by the micro-benchmark generator; do not edit.");
code.AppendLine("#nullable disable");
code.AppendLine("#pragma warning disable");
code.AppendLine("internal static partial class BenchmarkTable");
code.AppendLine("{");
// The cases are split into parts so no iterator compiles to a function over the engines' size limit.
const int CasesPerPart = 300;
var parts = 1;
code.AppendLine("    private static global::System.Collections.Generic.IEnumerable<BenchmarkCase> Part0()");
code.AppendLine("    {");

// NetWasm's own workloads run last, so the dotnet/performance cases keep their order and place.
foreach (var type in AllTypes(compilation.GlobalNamespace)
    .OrderBy(type => type.ToDisplayString().StartsWith("NetWasm.Workloads.", StringComparison.Ordinal))
    .ThenBy(type => type.ToDisplayString(), StringComparer.Ordinal))
{
    var benchmarks = type.GetMembers().OfType<IMethodSymbol>()
        .Where(method => method.GetAttributes().Any(attribute => Is(attribute, "Benchmark"))).ToArray();
    if (benchmarks.Length == 0 || type.IsAbstract || type.IsStatic) continue;
    if (type.DeclaredAccessibility != Accessibility.Public || type.ContainingType is { DeclaredAccessibility: not Accessibility.Public })
    {
        skipped.Add($"{type.ToDisplayString()}: not public");
        continue;
    }
    // A generic benchmark class runs once per [GenericTypeArguments] set.
    IEnumerable<INamedTypeSymbol> closed = type.IsGenericType
        ? type.GetAttributes().Where(attribute => Is(attribute, "GenericTypeArguments"))
            .Select(attribute => type.Construct([.. attribute.ConstructorArguments[0].Values.Select(value => (ITypeSymbol)value.Value!)]))
        : [type];
    foreach (var instanceType in closed)
    {
        if (!instanceType.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility == Accessibility.Public))
        {
            skipped.Add($"{instanceType.ToDisplayString()}: no public parameterless constructor");
            continue;
        }
        EmitType(instanceType, [.. benchmarks.Select(method => instanceType.Equals(type, SymbolEqualityComparer.Default)
            ? method : instanceType.GetMembers(method.Name).OfType<IMethodSymbol>().First(member => member.OriginalDefinition.Equals(method, SymbolEqualityComparer.Default)))]);
    }
}

code.AppendLine("        yield break;");
code.AppendLine("    }");
code.AppendLine("    public static global::System.Collections.Generic.IEnumerable<BenchmarkCase> All()");
code.AppendLine("    {");
for (var part = 0; part < parts; part++) code.AppendLine($"        foreach (var item in Part{part}()) yield return item;");
code.AppendLine("    }");
code.AppendLine("}");
File.WriteAllText(output, code.ToString());
File.WriteAllLines(Path.ChangeExtension(output, ".skipped.txt"), skipped);
Console.WriteLine($"{count} cases from {files.Length} files; {skipped.Count} skipped");
return 0;

void EmitType(INamedTypeSymbol type, IMethodSymbol[] benchmarks)
{
    var typeName = Name(type);
    var members = AllMembers(type).ToArray();
    // [Params] members, each with its literal values or a source member.
    var parameters = members.Where(member => member is IPropertySymbol or IFieldSymbol)
        .Select(member => (Member: member, Attribute: member.GetAttributes().FirstOrDefault(attribute =>
            Is(attribute, "Params") || Is(attribute, "ParamsSource") || Is(attribute, "ParamsAllValues"))))
        .Where(pair => pair.Attribute is not null).ToArray();
    var setups = members.OfType<IMethodSymbol>().Where(method => method.GetAttributes().Any(attribute => Is(attribute, "GlobalSetup"))).ToArray();
    var iterationSetups = members.OfType<IMethodSymbol>().Where(method => method.GetAttributes().Any(attribute => Is(attribute, "IterationSetup"))).ToArray();

    foreach (var benchmark in benchmarks)
    {
        if (benchmark.IsStatic || benchmark.IsGenericMethod || benchmark.DeclaredAccessibility != Accessibility.Public)
        {
            skipped.Add($"{typeName}.{benchmark.Name}: static, generic or not public");
            continue;
        }
        if (benchmark.Parameters.Any(parameter => parameter.RefKind != RefKind.None || parameter.Type.IsRefLikeType))
        {
            skipped.Add($"{typeName}.{benchmark.Name}: by-reference or ref struct parameter");
            continue;
        }
        var indent = "        ";
        var openers = new List<string>();
        var idParts = new List<string>();
        var assignments = new List<string>();
        var paramIndex = 0;
        foreach (var (member, attribute) in parameters)
        {
            var memberType = member is IPropertySymbol property ? property.Type : ((IFieldSymbol)member).Type;
            var variable = $"p{paramIndex++}";
            if (Is(attribute!, "Params"))
            {
                var values = attribute!.ConstructorArguments[0].Kind == TypedConstantKind.Array
                    ? attribute.ConstructorArguments[0].Values
                    : [attribute.ConstructorArguments[0]];
                openers.Add($"foreach (var {variable} in new {Name(memberType)}[] {{ {string.Join(", ", values.Select(value => $"({Name(memberType)})({value.ToCSharpString()})"))} }})");
            }
            else if (Is(attribute!, "ParamsSource"))
            {
                var source = (string)attribute!.ConstructorArguments[0].Value!;
                openers.Add($"foreach (var {variable} in new {typeName}().{source}{(members.OfType<IMethodSymbol>().Any(method => method.Name == source) ? "()" : "")})");
            }
            else if (memberType.SpecialType == SpecialType.System_Boolean)
            {
                openers.Add($"foreach (var {variable} in new bool[] {{ false, true }})");
            }
            else if (memberType.TypeKind == TypeKind.Enum)
            {
                var fields = memberType.GetMembers().OfType<IFieldSymbol>().Where(field => field.HasConstantValue);
                openers.Add($"foreach (var {variable} in new {Name(memberType)}[] {{ {string.Join(", ", fields.Select(field => $"{Name(memberType)}.{field.Name}"))} }})");
            }
            else
            {
                skipped.Add($"{typeName}.{benchmark.Name}: ParamsAllValues on {memberType}");
                goto NextBenchmark;
            }
            idParts.Add($"{member.Name}={{{variable}}}");
            assignments.Add($"b.{member.Name} = ({Name(memberType)}){variable};");
        }

        var applicableSetups = setups.Where(setup => AppliesTo(setup, benchmark, "GlobalSetup")).Select(setup => $"b.{setup.Name}();");
        var applicableIterationSetups = iterationSetups.Where(setup => AppliesTo(setup, benchmark, "IterationSetup")).Select(setup => $"b.{setup.Name}();");

        var argumentSets = new List<(string Id, string Arguments, string? Opener)>();
        var argumentAttributes = benchmark.GetAttributes().Where(attribute => Is(attribute, "Arguments")).ToArray();
        var argumentSource = benchmark.GetAttributes().FirstOrDefault(attribute => Is(attribute, "ArgumentsSource"));
        if (argumentAttributes.Length > 0)
        {
            foreach (var attribute in argumentAttributes)
            {
                var values = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Kind == TypedConstantKind.Array
                    ? attribute.ConstructorArguments[0].Values : attribute.ConstructorArguments;
                if (values.Length != benchmark.Parameters.Length)
                {
                    skipped.Add($"{typeName}.{benchmark.Name}: argument count");
                    continue;
                }
                var literal = values.Select((value, index) => Literal(value, benchmark.Parameters[index].Type)).ToArray();
                argumentSets.Add((string.Join(", ", values.Select(value => value.ToCSharpString().Replace("\"", "'").Replace("{", "[").Replace("}", "]"))), string.Join(", ", literal), null));
            }
        }
        else if (argumentSource is not null)
        {
            var source = (string)argumentSource.ConstructorArguments[0].Value!;
            var sourceMember = members.FirstOrDefault(member => member.Name == source);
            var call = sourceMember is IMethodSymbol ? $"{source}()" : source;
            var owner = sourceMember is { IsStatic: true } ? typeName : $"new {typeName}()";
            var cast = benchmark.Parameters.Length == 1
                ? $"({Name(benchmark.Parameters[0].Type)})ac"
                : string.Join(", ", benchmark.Parameters.Select((parameter, index) => $"({Name(parameter.Type)})((object[])ac)[{index}]"));
            argumentSets.Add(("{aic}", cast, $"var ai = 0; foreach (var a in {owner}.{call})"));
        }
        else if (benchmark.Parameters.Length == 0)
        {
            argumentSets.Add(("", "", null));
        }
        else
        {
            skipped.Add($"{typeName}.{benchmark.Name}: parameters without arguments");
            continue;
        }

        foreach (var (argumentId, arguments, opener) in argumentSets)
        {
            var block = new StringBuilder();
            var depth = indent;
            foreach (var line in openers)
            {
                block.AppendLine($"{depth}{line}");
                block.AppendLine($"{depth}{{");
                depth += "    ";
            }
            if (opener is not null)
            {
                block.AppendLine($"{depth}{{ {opener}");
                block.AppendLine($"{depth}{{");
                depth += "    ";
            }
            var idText = $"{type.ToDisplayString()}.{benchmark.Name}({string.Join(", ", idParts.Append(argumentId).Where(part => part.Length > 0))})";
            var invoke = $"b.{benchmark.Name}({arguments})";
            var returns = benchmark.ReturnsVoid ? $"{invoke};"
                : IsTask(benchmark.ReturnType) ? $"{invoke}.GetAwaiter().GetResult();"
                : $"Runner.Consume({invoke});";
            var captured = opener is not null ? "var ac = a; var aic = ai++; " : "";
            block.AppendLine($"{depth}{{ {captured}{string.Concat(parameters.Select((_, index) => $"var c{index} = p{index}; "))}yield return new BenchmarkCase($\"{EscapeId(idText)}\", () =>");
            block.AppendLine($"{depth}{{");
            block.AppendLine($"{depth}    var b = new {typeName}();");
            foreach (var assignment in assignments) block.AppendLine($"{depth}    {ReplaceParams(assignment, parameters.Length)}");
            foreach (var setup in applicableSetups) block.AppendLine($"{depth}    {setup}");
            var iteration = string.Concat(applicableIterationSetups.Select(setup => setup + " "));
            // Each timed body stays its own function: one dispatcher that inlined every
            // body made register allocation, and so timings, depend on unrelated cases.
            block.AppendLine($"{depth}    return [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)] () => {{ {iteration}{returns} }};");
            block.AppendLine($"{depth}}}); }}");
            if (opener is not null)
            {
                depth = depth[..^4];
                block.AppendLine($"{depth}}} }}");
            }
            foreach (var _ in openers)
            {
                depth = depth[..^4];
                block.AppendLine($"{depth}}}");
            }
            code.Append(block);
            count++;
            if (count % CasesPerPart == 0)
            {
                code.AppendLine("    }");
                code.AppendLine($"    private static global::System.Collections.Generic.IEnumerable<BenchmarkCase> Part{parts++}()");
                code.AppendLine("    {");
            }
        }
        NextBenchmark:;
    }
}

static string ReplaceParams(string assignment, int count)
{
    for (var index = 0; index < count; index++) assignment = assignment.Replace($"p{index};", $"c{index};");
    return assignment;
}

// An interpolated id: holes stay, other braces and quotes are escaped.
static string EscapeId(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", " ");

static bool IsTask(ITypeSymbol type) => type.ToDisplayString() is var name &&
    (name.StartsWith("System.Threading.Tasks.Task", StringComparison.Ordinal) || name.StartsWith("System.Threading.Tasks.ValueTask", StringComparison.Ordinal));

bool AppliesTo(IMethodSymbol setup, IMethodSymbol benchmark, string kind)
{
    var attribute = setup.GetAttributes().First(candidate => Is(candidate, kind));
    var targets = attribute.NamedArguments.Where(argument => argument.Key is "Target" or "Targets")
        .SelectMany(argument => argument.Value.Kind == TypedConstantKind.Array
            ? argument.Value.Values.Select(value => (string?)value.Value)
            : [(string?)argument.Value.Value])
        .Where(name => name is not null).ToArray();
    return targets.Length == 0 || targets.Contains(benchmark.Name);
}

static IEnumerable<ISymbol> AllMembers(INamedTypeSymbol type)
{
    for (var current = type; current is not null; current = current.BaseType)
        foreach (var member in current.GetMembers())
            yield return member;
}

static IEnumerable<INamedTypeSymbol> AllTypes(INamespaceSymbol root)
{
    foreach (var member in root.GetMembers())
    {
        if (member is INamespaceSymbol ns)
        {
            foreach (var type in AllTypes(ns)) yield return type;
        }
        else if (member is INamedTypeSymbol type && type.Locations.Any(location => location.IsInSource))
        {
            yield return type;
            foreach (var nested in Nested(type)) yield return nested;
        }
    }
}

static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type)
{
    foreach (var nested in type.GetTypeMembers())
    {
        yield return nested;
        foreach (var deeper in Nested(nested)) yield return deeper;
    }
}
