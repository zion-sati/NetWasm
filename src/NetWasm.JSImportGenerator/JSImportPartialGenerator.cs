using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NetWasm.JSImportGenerator;

/// <summary>
/// Gives each <c>[JSImport] static partial</c> method, the form .NET's browser
/// runtime declares imports in, the implementing declaration
/// <c>static extern partial</c>. The NetWasm compiler binds an extern [JSImport]
/// method itself, so nothing else is generated.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class JSImportPartialGenerator : IIncrementalGenerator
{
    private const string JSImportAttribute = "System.Runtime.InteropServices.JavaScript.JSImportAttribute";

    private static readonly DiagnosticDescriptor MissingAccessibility = new(
        "NWJS001",
        "A [JSImport] partial method needs an accessibility modifier",
        "Give [JSImport] partial method '{0}' an accessibility modifier, such as internal, so it can be implemented",
        "NetWasm.Interop",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var imports = context.SyntaxProvider.ForAttributeWithMetadataName(
            JSImportAttribute,
            static (node, _) => node is MethodDeclarationSyntax method &&
                method.Modifiers.Any(SyntaxKind.PartialKeyword) && method.Body is null &&
                method.ExpressionBody is null,
            static (attribute, _) => Describe(attribute));
        context.RegisterSourceOutput(imports, static (output, import) =>
        {
            if (import is null)
            {
                return;
            }
            if (import.Accessibility.Length == 0)
            {
                output.ReportDiagnostic(Diagnostic.Create(MissingAccessibility, import.Location, import.Name));
                return;
            }
            output.AddSource(import.HintName, import.Source);
        });
    }

    private static Import? Describe(GeneratorAttributeSyntaxContext attribute)
    {
        if (attribute.TargetSymbol is not IMethodSymbol { IsStatic: true, IsPartialDefinition: true } method ||
            method.PartialImplementationPart is not null)
        {
            return null;
        }
        var syntax = (MethodDeclarationSyntax)attribute.TargetNode;
        var accessibility = string.Join(" ", syntax.Modifiers
            .Where(modifier => modifier.Kind() is SyntaxKind.PublicKeyword or SyntaxKind.InternalKeyword or
                SyntaxKind.ProtectedKeyword or SyntaxKind.PrivateKeyword)
            .Select(modifier => modifier.Text));
        var nullable = attribute.SemanticModel.GetNullableContext(syntax.SpanStart)
            .AnnotationsEnabled() ? "enable" : "disable";
        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .Append("#nullable ").AppendLine(nullable);
        var types = method.ContainingType is { } type
            ? Enumerable.Repeat(type, 1).Concat(Containing(type)).Reverse().ToArray()
            : [];
        var @namespace = method.ContainingNamespace is { IsGlobalNamespace: false } containing
            ? containing.ToDisplayString()
            : null;
        if (@namespace is not null)
        {
            source.Append("namespace ").Append(@namespace).AppendLine();
            source.AppendLine("{");
        }
        foreach (var containingType in types)
        {
            source.Append("partial ").Append(Keyword(containingType)).Append(' ').Append(containingType.Name);
            if (containingType.TypeParameters.Length != 0)
            {
                source.Append('<').Append(string.Join(", ", containingType.TypeParameters.Select(parameter => parameter.Name)))
                    .Append('>');
            }
            source.AppendLine().AppendLine("{");
        }
        source.Append(accessibility).Append(" static extern partial ")
            .Append(method.ReturnsVoid ? "void" : method.ReturnType.ToDisplayString(TypeFormat))
            .Append(' ').Append(method.Name).Append('(')
            .Append(string.Join(", ", method.Parameters.Select(parameter =>
                $"{RefKind(parameter)}{parameter.Type.ToDisplayString(TypeFormat)} @{parameter.Name}")))
            .AppendLine(");");
        foreach (var _ in types)
        {
            source.AppendLine("}");
        }
        if (@namespace is not null)
        {
            source.AppendLine("}");
        }
        var hintName = string.Join(".", types.Select(containingType => containingType.MetadataName)
            .Append(method.Name)) + "." + syntax.SpanStart + ".JSImport.g.cs";
        return new Import(method.Name, accessibility, hintName, source.ToString(), syntax.Identifier.GetLocation());
    }

    private static ImmutableArray<INamedTypeSymbol> Containing(INamedTypeSymbol type)
    {
        var builder = ImmutableArray.CreateBuilder<INamedTypeSymbol>();
        for (var current = type.ContainingType; current is not null; current = current.ContainingType)
        {
            builder.Add(current);
        }
        return builder.ToImmutable();
    }

    private static string Keyword(INamedTypeSymbol type) => type switch
    {
        { IsRecord: true, TypeKind: TypeKind.Struct } => "record struct",
        { IsRecord: true } => "record",
        { TypeKind: TypeKind.Struct } => "struct",
        { TypeKind: TypeKind.Interface } => "interface",
        _ => "class",
    };

    private static string RefKind(IParameterSymbol parameter) => parameter.RefKind switch
    {
        Microsoft.CodeAnalysis.RefKind.Ref => "ref ",
        Microsoft.CodeAnalysis.RefKind.Out => "out ",
        Microsoft.CodeAnalysis.RefKind.In => "in ",
        _ => "",
    };

    // Equatable, so the incremental pipeline reuses the source of an unchanged import.
    private sealed record Import(string Name, string Accessibility, string HintName, string Source, Location Location);
}
