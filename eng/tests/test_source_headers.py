"""NetWasm's own sources carry the NetWasm notice with the license LICENSE-MAP.md gives their path.

Files ported from upstream keep upstream's notice. Third-party trees, template content that becomes
user code, and generated sources are left as they are.
"""

from __future__ import annotations

import re
import subprocess
import unittest
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
COPYRIGHT = "Copyright (c) 2026 Zion Sati and NetWasm contributors (https://github.com/zion-sati/NetWasm)"
NETWASM_LICENSES = frozenset({"LicenseRef-NetWasm-Community-1.0", "MIT", "Apache-2.0"})
SLASH_COMMENT_EXTENSIONS = frozenset({".cs", ".c", ".h", ".js", ".mjs", ".cjs"})
HASH_COMMENT_EXTENSIONS = frozenset({".py", ".sh"})
# Third-party sources, and template content that becomes the user's own project.
NOT_NETWASM_SOURCE = ("src/native/external/", "src/NetWasm.Templates/content/")
NOTICE_WORDS = re.compile(r"Copyright|Licensed to the|SPDX-License-Identifier")
LEADING_LINES = 25


@dataclass(frozen=True)
class LicenseRule:
    pattern: str
    license: str
    expression: re.Pattern[str]

    @property
    def specificity(self) -> int:
        return len(self.pattern.replace("*", ""))


def read_license_rules(license_map: Path) -> list[LicenseRule]:
    """The path rows of LICENSE-MAP.md's table, as glob patterns and their license."""
    rules = []
    for line in license_map.read_text(encoding="utf-8").splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 2 or "/" not in cells[0] or cells[0] == "Path":
            continue
        rules.append(LicenseRule(cells[0], cells[1], re.compile(glob_expression(cells[0]))))
    return rules


def glob_expression(pattern: str) -> str:
    expression = ""
    index = 0
    while index < len(pattern):
        if pattern.startswith("**", index):
            expression += ".*"
            index += 2
        elif pattern[index] == "*":
            expression += "[^/]*"
            index += 1
        else:
            expression += re.escape(pattern[index])
            index += 1
    return "^" + expression + "$"


def license_for(rules: list[LicenseRule], relative: str) -> str | None:
    """The license of the most specific row whose pattern matches the path."""
    matches = [rule for rule in rules if rule.expression.match(relative)]
    return max(matches, key=lambda rule: rule.specificity).license if matches else None


def comment_prefix(relative: str) -> str | None:
    suffix = Path(relative).suffix
    if suffix in SLASH_COMMENT_EXTENSIONS:
        return "//"
    if suffix in HASH_COMMENT_EXTENSIONS:
        return "#"
    return None


def notice_lines(prefix: str, license: str) -> list[str]:
    return [f"{prefix} {COPYRIGHT}.", f"{prefix} SPDX-License-Identifier: {license}"]


def is_generated(relative: str, lines: list[str]) -> bool:
    return relative.endswith(".g.cs") or any("<auto-generated" in line for line in lines[:5])


def body_start(lines: list[str]) -> int:
    """The first line after a shebang, where a notice belongs."""
    return 1 if lines and lines[0].startswith("#!") else 0


def has_other_notice(lines: list[str]) -> bool:
    """An existing notice in the leading comment lines, such as upstream's."""
    for line in lines[:LEADING_LINES]:
        stripped = line.strip()
        if stripped.startswith(("//", "/*", "*", "#")) and NOTICE_WORDS.search(stripped):
            return True
    return False


@dataclass(frozen=True)
class HeaderFinding:
    relative: str
    expected: list[str]


def tracked_files(root: Path) -> list[str]:
    output = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=True).stdout
    return sorted(path for path in output.decode("utf-8").split("\0") if path)


def notice_findings(root: Path, license_map: Path) -> tuple[int, list[HeaderFinding], list[str]]:
    """Checked file count, NetWasm sources without the right notice, and sources the map does not cover."""
    rules = read_license_rules(license_map)
    checked, findings, unmapped = 0, [], []
    for relative in tracked_files(root):
        prefix = comment_prefix(relative)
        if prefix is None or relative.startswith(NOT_NETWASM_SOURCE):
            continue
        path = root / relative
        if not path.is_file():
            continue
        lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
        if is_generated(relative, lines):
            continue
        license = license_for(rules, relative)
        if license is None:
            unmapped.append(relative)
            continue
        if license not in NETWASM_LICENSES:
            continue
        checked += 1
        start = body_start(lines)
        expected = notice_lines(prefix, license)
        if lines[start:start + 2] == expected:
            continue
        if any(COPYRIGHT in line for line in lines[:LEADING_LINES]) or not has_other_notice(lines):
            findings.append(HeaderFinding(relative, expected))
    return checked, findings, unmapped


class SourceHeaderTests(unittest.TestCase):
    def test_netwasm_sources_carry_the_notice_for_their_license(self) -> None:
        checked, findings, unmapped = notice_findings(ROOT, ROOT / "LICENSE-MAP.md")
        self.assertGreater(checked, 0)
        self.assertEqual([finding.relative for finding in findings], [])
        self.assertEqual(unmapped, [])

    def test_the_mit_license_names_its_copyright_holder(self) -> None:
        self.assertIn(COPYRIGHT, (ROOT / "LICENSES" / "MIT.txt").read_text(encoding="utf-8"))

    def test_the_most_specific_license_row_wins(self) -> None:
        rules = [
            LicenseRule(pattern, license, re.compile(glob_expression(pattern)))
            for pattern, license in (
                ("src/native/**", "MIT"),
                ("src/native/external/zlib-ng/**", "Zlib"),
                ("src/NetWasm.Compiler*/**", "LicenseRef-NetWasm-Community-1.0"),
            )
        ]
        self.assertEqual(license_for(rules, "src/native/external/zlib-ng/deflate.c"), "Zlib")
        self.assertEqual(license_for(rules, "src/native/libs/a.c"), "MIT")
        self.assertEqual(license_for(rules, "src/NetWasm.Compiler.Wasm/a.cs"), "LicenseRef-NetWasm-Community-1.0")
        self.assertIsNone(license_for(rules, "README.md"))

    def test_notices_follow_a_shebang(self) -> None:
        self.assertEqual(body_start(["#!/usr/bin/env python3", "import os"]), 1)
        self.assertEqual(body_start(["using System;"]), 0)


if __name__ == "__main__":
    unittest.main()
