"""Write src/NetWasm.Runtime/runtime_emscripten_stand_ins.c from the pinned Emscripten SDK's GL headers.

usage: eng/generate-emscripten-stand-ins.py

Emscripten implements the GL ES and WebGL functions, and a few others, in JavaScript. A NetWasm component has no
JavaScript, so native code that names them links these stand-ins instead: each does nothing and returns zero, so a GL
context is never created and a library such as Skia renders on the CPU, as on a desktop without OpenGL. The headers'
own declarations are included, so the compiler checks every signature.
"""

import os
import pathlib
import re
import sys

repository = pathlib.Path(__file__).resolve().parent.parent
root = pathlib.Path(os.environ.get("NETWASM_EMSDK_ROOT", pathlib.Path.home() / "emsdk-6.0.7"))
include = root / "upstream/emscripten/cache/sysroot/include"
# webgl1_ext.h declares its ANGLE instancing functions with other types than gl2ext.h; the Wasm signatures match.
headers = ["GLES2/gl2.h", "GLES2/gl2ext.h", "GLES3/gl3.h", "webgl/webgl2_ext.h"]
declaration = re.compile(r"(?:GL_APICALL|WEBGL_APICALL)\s+([^;(){}]+?)\s*GL_APIENTRY\s+(gl\w+)\s*\(([^;]*?)\)\s*;", re.S)

functions = {}
for header in headers:
    path = include / header
    if not path.exists():
        sys.exit(f"missing {path}")
    for match in declaration.finditer(path.read_text()):
        name = match.group(2)
        functions.setdefault(name, (" ".join(match.group(1).split()), " ".join(match.group(3).split())))

lines = [
    "// Copyright (c) 2026 Zion Sati and NetWasm contributors (https://github.com/zion-sati/NetWasm).",
    "// SPDX-License-Identifier: MIT",
    "// Generated by eng/generate-emscripten-stand-ins.py from the pinned Emscripten SDK's GL headers.",
    "",
    "// Stand-ins for functions Emscripten implements in JavaScript, which a NetWasm component does not have. Each",
    "// does nothing and returns zero: no GL context is created, so native code that can fall back to the CPU does.",
    "// Their archive is linked lazily after the project's, so only a program whose native code names one links it.",
    "",
    "#define GL_GLEXT_PROTOTYPES",
    "#include <stddef.h>",
] + [f"#include <{header}>" for header in headers] + [
    "",
    "// Weak, so a project archive that defines one, linked with it, wins.",
    "#define NETWASM_STAND_IN __attribute__((weak))",
    "",
    "NETWASM_STAND_IN int emscripten_has_asyncify(void) { return 0; }",
    "",
    "NETWASM_STAND_IN void *emscripten_webgl_get_proc_address(const char *name) { (void)name; return NULL; }",
    "",
]
for name in sorted(functions):
    result, parameters = functions[name]
    returned = " " if result == "void" else f" return ({result})0; "
    lines.append(f"NETWASM_STAND_IN {result} {name}({parameters}) {{{returned}}}")
target = repository / "src/NetWasm.Runtime/runtime_emscripten_stand_ins.c"
target.write_text("\n".join(lines) + "\n")
print(f"{len(functions)} GL functions")
