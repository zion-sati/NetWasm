namespace NetWasm.Hosting.Build.Tests;

// A platform provider catalog in the shape NetWasm.Hosting.Generator writes,
// for entry writers that select the providers an application links.
internal static class HostingCatalogFixture
{
    public static readonly string[] DefaultModules =
    [
        "wasi:cli/environment@0.2.11",
        "wasi:filesystem/types@0.2.11",
        "wasi:http/outgoing-handler@0.2.11",
        "wasi:io/streams@0.2.11",
        "wasi:random/random@0.2.11",
    ];

    public static void Write(string hostingRoot, params string[] modules)
    {
        Directory.CreateDirectory(hostingRoot);
        var providers = string.Join(",\n", (modules.Length == 0 ? DefaultModules : modules).Select(module => $$"""
                {
                  "module": "{{module}}",
                  "capability": "baseline",
                  "functions": []
                }
            """));
        File.WriteAllText(Path.Combine(hostingRoot, "platform-provider-catalog.generated.mjs"), $$"""
            // Generated by NetWasm.Hosting.Generator. Do not edit.
            function deepFreeze(value) {
              return Object.freeze(value);
            }

            export const platformProviderCatalog = deepFreeze({
              "schema": 1,
              "world": "netwasm:hosting-platform/preview2@1.0.0",
              "providers": [
            {{providers}}
              ]
            });

            """);
    }

    // The catalog the hosting package ships, for tests that read the real file.
    public static string ShippedHostingRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            var candidate = Path.Combine(directory.FullName, "src", "NetWasm.Hosting", "JavaScript");
            if (File.Exists(Path.Combine(candidate, "platform-provider-catalog.generated.mjs")))
            {
                return candidate;
            }
        }
        throw new InvalidOperationException("The shipped hosting JavaScript root was not found.");
    }
}
