using System.Linq;
using NetWasm.Compiler.ComponentModel;

namespace NetWasm.Compiler.Tests.Correctness;

// Every public static method of Vector128 whose parameters are vectors,
// elements, lane indices and shift counts, once for each element type it takes,
// computes what desktop's does: the ones that lower to Wasm SIMD by name and
// the ones that keep upstream's managed body, so no API is lowered that should
// not be, or lowered wrongly. Platform-defined results stay out: estimates,
// native conversions and shuffles, CreateScalarUnsafe's upper lanes, floating
// sums, and the math functions VectorMathFunctionCompilationTests compares
// within a few units in the last place. The calls are generated by reflection
// over desktop's Vector128 with eng/vector-surface.
public sealed class VectorSurfaceCorpusTests(CorrectnessTestRunner runner)
{
    [Theory]
    [InlineData(FinalWasmOptimization.O3)]
    [InlineData(FinalWasmOptimization.Oz)]
    public void EveryVector128MethodComputesWhatDesktopDoes(FinalWasmOptimization optimization) =>
        runner.Run(new(
            "VectorSurfaceCorpus",
            "NetWasm.Correctness.VectorSurface",
            Source,
            [.. Enumerable.Range(0, 27)])
        {
            Optimization = optimization,
            ExecuteWasm64 = true,
            ExecuteOptimizedWasm = true,
            ReportAllMismatches = true,
        });

