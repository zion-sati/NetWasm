                // around each sign bit, floats at their edges, NaN and infinity.
                private static T E<T>(int seed) where T : INumberBase<T> =>
                    typeof(T) == typeof(float) || typeof(T) == typeof(double)
                        ? T.CreateTruncating(s_floats[(seed * 7 + 3) % s_floats.Length])
                        : T.CreateTruncating(s_integers[(seed * 5 + 1) % s_integers.Length]);

                private static Vector128<T> V128<T>(int seed) where T : unmanaged, INumberBase<T>
                {
                    Span<T> lanes = stackalloc T[Vector128<T>.Count];
                    for (var i = 0; i < lanes.Length; i++) lanes[i] = E<T>(seed * 3 + i);
                    return Vector128.Create((ReadOnlySpan<T>)lanes);
                }

                // A shift count, within and past each lane width.
                private static int Count(int seed) => (seed * 13) % 70;

                // Every NaN is one value; the sign of zero stays.
                private static void Mix<T>(ref long h, T value) where T : INumberBase<T> =>
                    h = unchecked(h * 1000003 + (T.IsNaN(value) ? 0x7FF8 :
                        typeof(T) == typeof(float) ? BitConverter.SingleToInt32Bits(float.CreateTruncating(value)) :
                        typeof(T) == typeof(double) ? BitConverter.DoubleToInt64Bits(double.CreateTruncating(value)) :
