// The control flow of Avalonia's CommandBar.UpdateDynamicOverflow as the structurer received it: one try/finally around
// three nested try/finally blocks and a loop entered at its bottom test, whose body holds range checks that throw,
// with values carried across joins. The loop is structured twice, and the second copy crosses the protected region's
// boundary. That copy clipped its body by the blocks the first copy had claimed, so it came out empty and the loop's
// blocks were never emitted (NW1011: reachable original blocks were not emitted: 90, 91, ...). Conditions read the
// argument so nothing folds the shape away; every block must be emitted at every level.
public sealed class ReplicatedLoopAcrossRegionBoundaryCompilationTests
{
    [Theory]
    [InlineData(WasmTarget.Wasm32, FinalWasmOptimization.Oz)]
    [InlineData(WasmTarget.Wasm64, FinalWasmOptimization.Oz)]
    [InlineData(WasmTarget.Wasm32, FinalWasmOptimization.Os)]
    [InlineData(WasmTarget.Wasm32, FinalWasmOptimization.O1)]
    [InlineData(WasmTarget.Wasm32, FinalWasmOptimization.O3)]
    [InlineData(WasmTarget.Wasm32, FinalWasmOptimization.O0)]
    public void EveryBlockOfALoopReplicatedAcrossARegionBoundaryIsEmitted(WasmTarget target, FinalWasmOptimization optimization)
    {
        using var assets = TestAssets.Create();
        var path = Build(assets);

        var result = NetWasmCompiler.Compile(new(path, [assets.CoreLib], "ReplicatedLoop.EntryPoint", "Run",
            [new("run", "ReplicatedLoop.EntryPoint", "Run")], Target: target, Optimization: optimization,
            ReferenceAssemblyAliases: ImmutableDictionary<string, string>.Empty.Add("System.Private.CoreLib", "NetWasm.CoreLib"),
            WitPath: Path.Combine(assets.Root, "wit", "netwasm-platform-1.0.0"),
            WitWorld: "netwasm:platform/platform@1.0.0"));

        CompilerTestSupport.ValidateWithNode(result.ApplicationModule, assets.Directory);
    }

